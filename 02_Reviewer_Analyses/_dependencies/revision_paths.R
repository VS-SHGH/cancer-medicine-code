validate_revision_paths <- function(required = c(
  "BULK_STEP1_RDATA", "BULK_CLUSTER_RDATA", "BULK_DEA_RDATA",
  "CLINICAL_SUBTYPE_XLSX", "CLINICAL_SURGERY_XLSX",
  "PUBLIC_SC_RAW_QS", "EXTERNAL_GSE141801_DIR", "EXTERNAL_GSE39645_DIR"
)) {
  vals <- mget(required, envir = .GlobalEnv, inherits = TRUE)
  ok <- vapply(vals, file.exists, logical(1))
  if (!all(ok)) stop("Missing required inputs: ", paste(names(ok)[!ok], collapse = ", "))
  invisible(ok)
}
